    /**
     * Validates the `replaceFile` action.
     *
     * @return void
     * @since 5.3
     */
    public function validateReplaceFile()
    {
        WCF::getSession()->checkPermissions(['admin.content.cms.canManageMedia']);

        if (!$this->getSingleObject()->canManage()) {
            throw new PermissionDeniedException();
        }

        $this->parameters['__files']->validateFiles(
            new MediaReplaceUploadFileValidationStrategy($this->getSingleObject()->getDecoratedObject())
        );
    }

    /**
     * Replaces the actual file of a media file.
     *
     * @return array{
     *  errors: array<int, array{
     *      filename: string,
     *      filesize: int,
     *      errorType: string,
     *  }>,
     *  media: array<int, mixed[]>,
     * }
     * @since 5.3
     */
    public function replaceFile()
    {
        $media = $this->getSingleObject()->getDecoratedObject();

        $result = [
            'errors' => [],
            'media' => [],
        ];

        /** @var UploadFile[] $files */
        $files = $this->parameters['__files']->getFiles();
        foreach ($files as $uploadFile) {
            if ($uploadFile->getValidationErrorType() === '') {
                $file = $this->createFileFromUpload($uploadFile);
                if ($file !== null) {
                    // The previous file is deleted by the builder.
                    (new UpdateMedia(
                        MediaBuilder::forUpdate($media)
                            ->setFile($file)
                            ->setFileUpdateTime(\TIME_NOW)
                    ))();

                    $result['media'][$uploadFile->getInternalFileID()] = $this->getMediaData(new Media($media->mediaID));

                    continue;
                }

                $uploadFile->setValidationErrorType('uploadFailed');
            }

            $result['errors'][$uploadFile->getInternalFileID()] = [
                'filename' => $uploadFile->getFilename(),
                'filesize' => $uploadFile->getFilesize(),
                'errorType' => $uploadFile->getValidationErrorType(),
            ];
        }

        return $result;
    }
