    #[\Override]
    public function validateUpdate()
    {
        WCF::getSession()->checkPermissions(['admin.content.cms.canManageMedia']);

        if ($this->objects === []) {
            $this->readObjects();

            if ($this->objects === []) {
                throw new UserInputException('objectIDs');
            }
        }

        if (WCF::getSession()->hasPermission('admin.content.cms.canOnlyAccessOwnMedia')) {
            foreach ($this->getObjects() as $media) {
                if ($media->userID !== WCF::getUser()->userID) {
                    throw new PermissionDeniedException();
                }
            }
        }

        $this->readInteger('categoryID', true, 'data');
        $this->readInteger('languageID', true, 'data');
        $this->readBoolean('isMultilingual', true, 'data');
        $this->readInteger('captionEnableHtml', true, 'data');

        if (\count(LanguageFactory::getInstance()->getLanguages()) > 1) {
            // languageID: convert zero to null
            if ($this->parameters['data']['languageID'] === 0) {
                $this->parameters['data']['languageID'] = null;
            }

            // isMultilingual: convert boolean to integer
            $this->parameters['data']['isMultilingual'] = \intval($this->parameters['data']['isMultilingual']);
        } else {
            $this->parameters['data']['isMultilingual'] = 0;
            $this->parameters['data']['languageID'] = WCF::getLanguage()->languageID;
        }

        // if data is not multilingual, a language id has to be given
        if ($this->parameters['data']['isMultilingual'] === 0 && $this->parameters['data']['languageID'] === null) {
            throw new UserInputException('languageID');
        }

        // check language id
        if (
            $this->parameters['data']['languageID'] !== null
            && LanguageFactory::getInstance()->getLanguage($this->parameters['data']['languageID']) === null
        ) {
            throw new UserInputException('languageID');
        }

        // check category id
        if ($this->parameters['data']['categoryID'] !== 0) {
            $category = CategoryHandler::getInstance()->getCategory($this->parameters['data']['categoryID']);
            if ($category === null || $category->getObjectType()->objectType !== 'com.woltlab.wcf.media.category') {
                throw new UserInputException('categoryID');
            }
        }
    }

    #[\Override]
    public function update()
    {
        if ($this->objects === []) {
            $this->readObjects();
        }

        $data = $this->parameters['data'] ?? [];

        foreach ($this->getObjects() as $mediaEditor) {
            $media = $mediaEditor->getDecoratedObject();
            $builder = MediaBuilder::forUpdate($media);

            if (\array_key_exists('categoryID', $data)) {
                $builder->setCategoryID($data['categoryID'] ?: null);
            }
            if (isset($data['captionEnableHtml'])) {
                $builder->setCaptionEnableHtml((bool)$data['captionEnableHtml']);
            }

            $isMultilingual = $data['isMultilingual'] ?? $media->isMultilingual;
            $languageID = \array_key_exists('languageID', $data) ? $data['languageID'] : $media->languageID;
            if (isset($data['isMultilingual'])) {
                $builder->setCustomProperty('isMultilingual', $isMultilingual);
            }
            if (\array_key_exists('languageID', $data)) {
                $builder->setCustomProperty('languageID', $languageID);
            }

            if (\count($this->objects) === 1) {
                foreach (['title', 'caption', 'altText'] as $columnName) {
                    if (!isset($this->parameters[$columnName])) {
                        continue;
                    }

                    $values = $this->getL10nValuesFromParameter(
                        $this->parameters[$columnName],
                        $isMultilingual ? null : $languageID,
                        $columnName === 'caption' ? null : 255
                    );

                    match ($columnName) {
                        'title' => $builder->setTitle($values),
                        'caption' => $builder->setCaption($values),
                        'altText' => $builder->setAltText($values),
                    };
                }

                if (!empty($this->parameters['aclValues'])) {
                    $builder->setAclValues([
                        'allowAll' => (bool)($this->parameters['aclValues']['allowAll'] ?? true),
                        'user' => \array_map(\intval(...), $this->parameters['aclValues']['user'] ?? []),
                        'group' => \array_map(\intval(...), $this->parameters['aclValues']['group'] ?? []),
                    ]);
                }
            }

            (new UpdateMedia($builder))();
        }
    }

    /**
     * Converts the values submitted by the legacy editor into l10n values.
     *
     * @param string|array<int, string> $parameter
     * @return array<non-negative-int, string>
     */
    private function getL10nValuesFromParameter(
        string|array $parameter,
        ?int $monolingualLanguageID,
        ?int $maximumLength
    ): array {
        $shorten = static fn(string $value): string => $maximumLength === null
            ? $value
            : \mb_substr($value, 0, $maximumLength);

        if ($monolingualLanguageID !== null) {
            $value = \is_array($parameter) ? ($parameter[$monolingualLanguageID] ?? '') : $parameter;

            return [L10nStorage::MONOLINGUAL => $shorten($value)];
        }

        $values = [];
        foreach (LanguageFactory::getInstance()->getLanguages() as $language) {
            $value = \is_array($parameter) ? ($parameter[$language->languageID] ?? '') : $parameter;
            $values[$language->languageID] = $shorten($value);
        }

        return $values;
    }

    #[\Override]
    public function validateGetSearchResultList()
    {
        if (!WCF::getSession()->hasPermission('admin.content.cms.canManageMedia') && !WCF::getSession()->hasPermission('admin.content.cms.canUseMedia')) {
            throw new PermissionDeniedException();
        }

        $this->readString('searchString', true);
        $this->readInteger('categoryID', true);

        $this->readBoolean('imagesOnly', true);

        $this->readString('mode');
        if ($this->parameters['mode'] !== 'editor' && $this->parameters['mode'] !== 'select') {
            throw new UserInputException('mode');
        }

        $this->readInteger('pageNo', true);
        if ($this->parameters['pageNo'] === 0) {
            $this->parameters['pageNo'] = 1;
        }
        if ($this->parameters['pageNo'] < 1) {
            throw new UserInputException('pageNo');
        }
    }

    #[\Override]
    public function getSearchResultList()
    {
        $mediaList = new MediaList();
        $mediaList->addSearchConditions($this->parameters['searchString']);
        if (WCF::getSession()->hasPermission('admin.content.cms.canOnlyAccessOwnMedia')) {
            $mediaList->getConditionBuilder()->add('media.userID = ?', [WCF::getUser()->userID]);
        }
        if ($this->parameters['imagesOnly'] === true) {
            $mediaList->getConditionBuilder()->add('media.isImage = ?', [1]);
        }
        if ($this->parameters['categoryID'] !== 0) {
            if ($this->parameters['categoryID'] === -1) {
                $mediaList->getConditionBuilder()->add('media.categoryID IS NULL');
            } else {
                $mediaList->getConditionBuilder()->add('media.categoryID = ?', [$this->parameters['categoryID']]);
            }
        }
        $mediaList->sqlOrderBy = 'media.uploadTime DESC, media.mediaID DESC';
        $mediaList->sqlLimit = static::ITEMS_PER_MANAGER_DIALOG_PAGE;
        $mediaList->sqlOffset = ($this->parameters['pageNo'] - 1) * static::ITEMS_PER_MANAGER_DIALOG_PAGE;
        $mediaList->readObjects();

        if ($mediaList->getObjectIDs() === []) {
            // check if page is requested that might have existed but does not exist anymore due to deleted
            // media files
            if ($this->parameters['pageNo'] > 1 && $this->parameters['searchString'] === '' && $this->parameters['categoryID'] === 0) {
                // request media dialog page with highest page number
                $parameters = $this->parameters;
                $parameters['pageNo'] = \ceil($mediaList->countObjects() / static::ITEMS_PER_MANAGER_DIALOG_PAGE);

                return (new self($this->objects, 'getSearchResultList', $parameters))->executeAction()['returnValues'];
            }

            return [
                'template' => WCF::getLanguage()->getDynamicVariable('wcf.media.search.noResults'),
            ];
        }

        return [
            'media' => $this->getI18nMediaData($mediaList),
            'pageCount' => \ceil($mediaList->countObjects() / static::ITEMS_PER_MANAGER_DIALOG_PAGE),
            'pageNo' => $this->parameters['pageNo'],
            'template' => WCF::getTPL()->render('wcf', 'mediaListItems', [
                'mediaList' => $mediaList,
                'mode' => $this->parameters['mode'],
            ]),
        ];
    }

